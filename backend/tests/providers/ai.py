def _usage() -> Usage:
    return Usage(input_tokens=0, output_tokens=0, cost_usd=0.0, calls=0)


def _require_fixture(conversation: Conversation) -> None:
    if conversation.id not in _SUMMARIES:
        raise JudgeError("Нет заготовки для этого диалога")


async def summarize(conversation: Conversation) -> Summary:
    _require_fixture(conversation)
    return Summary(**_SUMMARIES[conversation.id], usage=_usage())


async def translate(conversation: Conversation) -> Translation:
    """Return translated turns and usage together, retaining original turn IDs."""
    _require_fixture(conversation)
    if conversation.language == "RU":
        return Translation(turns=[], usage=_usage())
    texts = _TRANSLATIONS.get(conversation.id)
    if texts is None or len(texts) != len(conversation.transcript):
        raise JudgeError("Нет заготовки перевода для этого транскрипта")
    return Translation(
        turns=[TranslatedTurn(idx=turn.idx, text=text) for turn, text in zip(conversation.transcript, texts)],
        usage=_usage(),
    )


async def coach(
    conversation: Conversation, items: list[tuple[Criterion, JudgeResult]]
) -> list[Tip]:
    _require_fixture(conversation)
    tips = []
    for criterion, result in items:
        if result.answer == "na":
            continue
        if criterion.type == "flag":
            weak = result.answer == "yes"
        elif criterion.type == "scale":
            weak = result.answer < max(step.value for step in criterion.scale or [])
        else:
            weak = result.answer == "no"
        if not weak:
            continue
        if criterion.id not in _TIPS:
            raise JudgeError("Нет заготовки совета для этого критерия")
        tip, example = _TIPS[criterion.id]
        if conversation.id == "p1-ru-007" and criterion.id == "consultation":
            example = "Поручение вы нашли. Уточню, на каком этапе проверки можно повторить вывод средств, и сообщу вам."
        if conversation.id == "p1-ru-007" and criterion.id == "closing":
            example = "Итак, подайте поручение «Изменение сведений». Уточню для вас, когда можно повторить вывод. Есть ли ещё вопросы? Хорошего дня!"
        if conversation.id == "p4-ru-001" and criterion.id == "consultation":
            example = "Техническая поддержка не рекомендует ценные бумаги. Уточню, куда вам обратиться по вопросу закрепления персонального менеджера."
        tips.append(Tip(criterion_id=criterion.id, tip=tip, example=example))
    return tips


async def suggest_criterion(title: str, draft: str, type: str) -> CriterionSuggestion:
    title, draft = title.strip(), draft.strip()
    if not title or not draft:
        raise JudgeError("Укажите название и черновик правила")
    if type not in {"binary", "scale", "flag"}:
        raise JudgeError("Неизвестный тип критерия")
    scale = None
    if type == "scale":
        description = f"Оцените критерий «{title}» по наблюдаемым действиям оператора: {draft.rstrip('.')}. Учитывайте только подтверждённые репликами действия."
        scale = [
            ScaleStep(value=2, description="Все условия правила выполнены и подтверждены диалогом"),
            ScaleStep(value=1, description="Условия выполнены частично; конкретный пропуск подтверждён диалогом"),
            ScaleStep(value=0, description="Требуемое действие отсутствует либо противоречит правилу"),
        ]
    else:
        lead = "Да, если в диалоге подтверждено нарушение" if type == "flag" else "Да, если в диалоге подтверждено действие оператора"
        description = f"{lead} по критерию «{title}»: {draft.rstrip('.')}. Если подтверждения нет, ставьте «Нет» и укажите проверенный фрагмент."
    return CriterionSuggestion(description=description, na_condition=None, scale=scale)
